import { defineConfig } from "@lovable.dev/vite-tanstack-config";

// Deployment target is controlled by the NITRO_PRESET env var:
//   (unset)      -> Lovable / Cloudflare Workers (default, do not change)
//   "vercel"     -> Vercel build output API (.vercel/output)
//   "node-server"-> Node server for Render / any VPS (.output/server/index.mjs)
const preset = process.env.NITRO_PRESET;

export default defineConfig({
  tanstackStart: {
    // Redirect TanStack Start's bundled server entry to src/server.ts (our SSR error wrapper).
    // nitro/vite builds from this
    server: { entry: "server" },
  },
  ...(preset ? { nitro: { preset } } : {}),
});
